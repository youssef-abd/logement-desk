"""One-off generator for desk/public/geo.js (Lyon urban area outlines).
Source: geo.api.gouv.fr (IGN Admin Express, Licence Ouverte Etalab). Needs network."""
import json, math, urllib.request, urllib.parse
from pathlib import Path

API = "https://geo.api.gouv.fr/communes?"
LAT0, W, MAX_PTS = 45.75, 1000, 80
ARR = ["Lyon 1er"] + [f"Lyon {n}e" for n in range(2, 10)]
AREAS = {f"6900{n}": (ARR[n - 1], dict(codePostal=f"6900{n}", type="arrondissement-municipal"))
         for n in range(1, 10)}
for postal, insee, name in [("69100", "69266", "Villeurbanne"), ("69300", "69034", "Caluire"),
                            ("69500", "69029", "Bron"), ("69200", "69259", "Vénissieux"),
                            ("69600", "69149", "Oullins"), ("69190", "69199", "Saint-Fons"),
                            ("69130", "69081", "Écully")]:
    AREAS[postal] = (name, dict(code=insee))

def fetch(params):
    q = urllib.parse.urlencode({**params, "fields": "nom,code", "format": "geojson", "geometry": "contour"})
    with urllib.request.urlopen(API + q, timeout=30) as r:
        feats = json.load(r)["features"]
    assert len(feats) == 1, (params, [f["properties"] for f in feats])
    return feats[0]

def outer_rings(geom):
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    return [p[0] for p in polys]  # outer ring only, holes ignored

def project(ring):
    return [(lon * math.cos(math.radians(LAT0)), -lat) for lon, lat in ring]

def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    d = math.hypot(x2 - x1, y2 - y1) or 1e-12
    dists = [abs((x2 - x1) * (y1 - y) - (x1 - x) * (y2 - y1)) / d for x, y in pts[1:-1]]
    i = max(range(len(dists)), key=dists.__getitem__)
    if dists[i] <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[:i + 2], tol)[:-1] + dp(pts[i + 1:], tol)

def dp_ring(r, tol):
    # split the closed ring at the point farthest from its start, then simplify both halves
    r = r[:-1]
    k = max(range(len(r)), key=lambda i: math.dist(r[0], r[i]))
    return dp(r[:k + 1], tol)[:-1] + dp(r[k:] + [r[0]], tol)

def simplify(rings):
    tol = 1e-6
    while True:
        out = [dp_ring(r, tol) for r in rings]
        if sum(len(r) for r in out) <= MAX_PTS:
            return [r for r in out if len(r) >= 3]
        tol *= 1.15

def centroid(ring):
    a = cx = cy = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        c = x1 * y2 - x2 * y1
        a += c; cx += (x1 + x2) * c; cy += (y1 + y2) * c
    return cx / (3 * a), cy / (3 * a)

def main():
    shapes = {}
    for postal, (name, params) in AREAS.items():
        f = fetch(params)
        print(postal, name, "<-", f["properties"])
        shapes[postal] = simplify([project(r) for r in outer_rings(f["geometry"])])
    xs = [x for rs in shapes.values() for r in rs for x, _ in r]
    ys = [y for rs in shapes.values() for r in rs for _, y in r]
    x0, y0, s = min(xs), min(ys), W / (max(xs) - min(xs))
    H = round((max(ys) - y0) * s)
    fmt = lambda v: f"{v:.1f}".rstrip("0").rstrip(".")
    geo = {}
    for postal, rings in shapes.items():
        rings = [[((x - x0) * s, (y - y0) * s) for x, y in r] for r in rings]
        path = "".join("M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in r) + "Z" for r in rings)
        cx, cy = centroid(max(rings, key=lambda r: abs(centroid_area(r))))
        geo[postal] = f'{{ name: {json.dumps(AREAS[postal][0], ensure_ascii=False)}, path: "{path}", cx: {round(cx)}, cy: {round(cy)} }}'
    body = ",\n  ".join(f'"{k}": {v}' for k, v in geo.items())
    Path(__file__).resolve().parent.parent.joinpath("desk/public/geo.js").write_text(
        "// Lyon urban area outlines. Source: geo.api.gouv.fr (IGN Admin Express, Licence Ouverte Etalab). "
        "Generated by scripts/make_geo.py: do not edit by hand.\n"
        f'export const VIEWBOX = "0 0 {W} {H}";\nexport const GEO = {{\n  {body}\n}};\n', encoding="utf-8")

def centroid_area(r):
    return sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(r, r[1:] + r[:1])) / 2

if __name__ == "__main__":
    main()
